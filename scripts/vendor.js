// Copies third-party browser files into src/vendor and builds src/js/icons.js.
// Run after `npm install` when updating dependencies: npm run vendor
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const nm = (...p) => path.join(root, 'node_modules', ...p);
const out = (...p) => path.join(root, 'src', 'vendor', ...p);

fs.mkdirSync(out('leaflet', 'images'), { recursive: true });
fs.copyFileSync(nm('adhan', 'lib', 'bundles', 'adhan.umd.min.js'), out('adhan.umd.min.js'));
fs.copyFileSync(nm('adhan', 'LICENSE'), out('adhan.LICENSE'));
for (const f of ['leaflet.js', 'leaflet.css']) fs.copyFileSync(nm('leaflet', 'dist', f), out('leaflet', f));
for (const f of fs.readdirSync(nm('leaflet', 'dist', 'images'))) fs.copyFileSync(nm('leaflet', 'dist', 'images', f), out('leaflet', 'images', f));
fs.copyFileSync(nm('leaflet', 'LICENSE'), out('leaflet', 'LICENSE'));

const icons = ['clock', 'alarm-clock', 'timer', 'hourglass', 'globe', 'compass', 'settings', 'calendar-days', 'moon-star',
  'sun', 'moon', 'plus', 'trash-2', 'play', 'pause', 'rotate-ccw', 'flag', 'bell', 'bell-off', 'volume-2', 'volume-x',
  'chevron-left', 'chevron-right', 'map-pin', 'search', 'locate-fixed', 'x', 'pencil', 'check', 'navigation', 'circle-play', 'link',
  'music', 'file-audio', 'languages', 'palette', 'sparkles', 'power', 'info', 'sunrise', 'sunset', 'list', 'square',
  'calendar-clock', 'maximize', 'circle-alert', 'house', 'repeat', 'monitor', 'map'];
const lines = ['// Generated by scripts/vendor.js from lucide-static (ISC licence). Do not edit by hand.', 'export const ICONS = {'];
for (const name of icons) {
  const svg = fs.readFileSync(nm('lucide-static', 'icons', name + '.svg'), 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, '');
  lines.push(`  '${name}': '${inner.replace(/'/g, "\\'")}',`);
}
lines.push('};', '',
  'export function icon(name, cls = \'\') {',
  '  return `<svg class="icon ${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${ICONS[name] || \'\'}</svg>`;',
  '}', '');
fs.writeFileSync(path.join(root, 'src', 'js', 'icons.js'), lines.join('\n'));
fs.copyFileSync(nm('lucide-static', 'LICENSE'), out('lucide.LICENSE'));
console.log('vendor files updated');
